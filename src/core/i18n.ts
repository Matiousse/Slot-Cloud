const DICTS: Record<string, Dict> = { en, fr, es, de, pt };
let dict: Dict = en;
let isSocial = false;
export let lang = 'en';

export function setLanguage(code: string, socialCasino = false) {
  const c = (code || 'en').toLowerCase().slice(0, 2);
  lang = DICTS[c] ? c : 'en';
  dict = DICTS[lang];
  isSocial = socialCasino;
  document.documentElement.lang = lang;
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  let s = (isSocial && lang === 'en' && social[key]) || dict[key] || en[key] || key;
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
